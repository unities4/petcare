import { isIos } from '../../lib/standalone'

/**
 * Показывается, пока приложение открыто во вкладке. На iOS баннера установки не
 * существует и события beforeinstallprompt тоже — подсказку рисуем сами.
 */
export function InstallHint() {
  return (
    <div className="card hint">
      <strong style={{ color: 'var(--text)' }}>Установите приложение на телефон</strong>
      {isIos() ? (
        <ol>
          <li>Нажмите «Поделиться» внизу Safari</li>
          <li>Выберите «На экран „Домой“»</li>
          <li>Запускайте с иконки, а не из браузера</li>
        </ol>
      ) : (
        <ol>
          <li>Откройте меню браузера</li>
          <li>Выберите «Установить приложение»</li>
        </ol>
      )}
      <p style={{ marginBottom: 0, marginTop: 10 }}>
        Без установки не будут работать напоминания: iOS присылает их только тем
        приложениям, которые запущены с домашнего экрана.
      </p>
    </div>
  )
}
